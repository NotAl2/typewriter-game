def build_face(name, glyphs, gw, gh, advance, line_height, baseline, ink,
               cols=16):
    """Rasterise a glyph table into atlas + metrics + .fnt."""
    chars = sorted(glyphs.keys(), key=ord)
    rows = (len(chars) + cols - 1) // cols
    atlas = Canvas(cols * gw, rows * gh)

    meta = {
        "name": name,
        "glyph_w": gw,
        "glyph_h": gh,
        "advance": advance,
        "line_height": line_height,
        "baseline": baseline,
        "cols": cols,
        "chars": {},
    }

    for idx, ch in enumerate(chars):
        gx = (idx % cols) * gw
        gy = (idx // cols) * gh
        art = glyphs[ch]
        assert len(art) == gh, "%s glyph %r has %d rows, expected %d" % (
            name, ch, len(art), gh)
        for j, row in enumerate(art):
            assert len(row) == gw, "%s glyph %r row %d is %d wide, expected %d" % (
                name, ch, j, len(row), gw)
            for i, c in enumerate(row):
                if c == "#":
                    atlas.set(gx + i, gy + j, ink)
        meta["chars"][ch] = {"x": gx, "y": gy}

    os.makedirs(OUT, exist_ok=True)
    png = os.path.join(OUT, name + ".png")
    atlas.save(png)
    with open(os.path.join(OUT, name + ".json"), "w") as f:
        json.dump(meta, f, indent=1, sort_keys=True)

    # AngelCode BMFont text format, for Godot Label/RichTextLabel use
    lines = [
        'info face="%s" size=%d bold=0 italic=0 charset="" unicode=1 '
        'stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0' % (name, gh),
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0"
        % (line_height, baseline, atlas.w, atlas.h),
        'page id=0 file="%s.png"' % name,
        "chars count=%d" % len(chars),
    ]
    for ch in chars:
        m = meta["chars"][ch]
        lines.append(
            "char id=%-5d x=%-4d y=%-4d width=%-3d height=%-3d xoffset=0 "
            "yoffset=0 xadvance=%d page=0 chnl=15" % (
                ord(ch), m["x"], m["y"], gw, gh, advance)
        )
    lines.append("kernings count=0")
    with open(os.path.join(OUT, name + ".fnt"), "w") as f:
        f.write("\n".join(lines) + "\n")

    return atlas, meta


def main():
    ink = C("ink")
    build_face("type_5x7", G57, 5, 7, 6, 9, 6, ink)
    build_face("tiny_3x5", G35, 3, 5, 4, 6, 5, ink)
    print("fonts: type_5x7 (%d glyphs), tiny_3x5 (%d glyphs) -> %s"
          % (len(G57), len(G35), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
