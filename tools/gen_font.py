"""Bitmap font generator.

Produces three artefacts per face:
  * <name>.png   glyph atlas, one cell per glyph, transparent background
  * <name>.json  metrics for PageRenderer's hand-rolled glyph drawing
  * <name>.fnt   AngelCode BMFont, so Godot Labels can use the same face

The page face is 5x7 with a 6px advance. That advance is what sets the
typewriter's line width (24 columns) and therefore the carriage's travel
distance, so changing it means retuning Carriage.gd.

Glyphs are authored as ASCII art below - '#' is ink, '.' is paper. Editing a
letterform means editing the picture of it, which is the whole point.
"""

